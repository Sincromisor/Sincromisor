import { expect, it, vi } from "vitest";
import { ChatMessageService } from "../chatMessageService";

it("更新時だけスナップショットを置き換え、古い履歴・順序・件数・購読解除を保つ", () => {
    const service = ChatMessageService.getService();
    const empty = service.getSnapshot();
    expect(service.getSnapshot()).toBe(empty);
    const listener = vi.fn();
    const stop = service.subscribeSnapshot(listener);
    for (let i = 0; i < 31; i++) service.writeSystemMessage(`履歴${i}`);
    const before = service.getSnapshot();
    expect(before.messages).toHaveLength(30);
    expect(empty.messages).toHaveLength(0);
    const input = { ...before.messages[1].message, message: "更新" };
    service.writeMessage(input, true);
    input.message = "呼び出し元で変更";
    const after = service.getSnapshot();
    expect(after).not.toBe(before);
    expect(after.messages[0]).toBe(before.messages[0]);
    expect(after.messages[1].message.message).toBe("更新");
    expect(after.messages[1].renderMode).toBe("trusted_html");
    expect(before.messages[1].message.message).toBe("履歴29");
    service.setSystemIcon("/new.webp");
    expect(service.getSnapshot().messages).toBe(after.messages);
    expect(after.systemIconUrl).toBe(empty.systemIconUrl);
    const icon = service.getSnapshot();
    listener.mockClear();
    service.setSystemIcon("/new.webp");
    expect(service.getSnapshot()).toBe(icon);
    expect(listener).not.toHaveBeenCalled();
    service.writeErrorMessage("同一エラー");
    const error = service.getSnapshot();
    service.writeErrorMessage("同一エラー");
    expect(service.getSnapshot()).toBe(error);
    expect(listener).toHaveBeenCalledOnce();
    stop();
    listener.mockClear();
    service.writeSystemMessage("解除後");
    expect(listener).not.toHaveBeenCalled();
});

it("重要エラーは会話の保持上限で消えず、明示的に閉じた後は再発を通知する", () => {
    const service = ChatMessageService.getService();
    service.writeErrorMessage("保存しておくエラー");
    const notice = service.getSnapshot().importantNotice;
    for (let i = 0; i < 31; i++) service.writeSystemMessage(`続く会話${i}`);
    expect(service.getSnapshot().importantNotice).toBe(notice);
    service.dismissImportantNotice();
    expect(service.getSnapshot().importantNotice).toBeUndefined();
    service.writeErrorMessage("保存しておくエラー");
    expect(service.getSnapshot().importantNotice?.message.message).toBe("保存しておくエラー");
});
