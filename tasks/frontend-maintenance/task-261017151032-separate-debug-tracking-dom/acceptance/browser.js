async (page) => {
    await page.goto("http://127.0.0.1:5173/simple-vrm/");
    await page.locator("#debugConsole").waitFor({ state: "attached" });
    await page.evaluate(() => document.querySelector("dialog")?.close());
    await page.mouse.click(10, 100);
    const initial = await page.evaluate(async () => {
        const source = name => performance.getEntriesByType("resource").find(entry => entry.name.split("?")[0].endsWith(`/${name}`)).name;
        const { CharacterGaze } = await import(source("characterGaze.ts"));
        const { SincroAppController } = await import(source("sincroAppController.ts"));
        const { setupRtcRemoteTrackHandlers } = await import("/features/rtc/rtcRemoteTrackHandlers.ts");
        const { DebugConsoleManager } = await import(source("debugConsoleManager.ts"));
        const ids = ["characterGazeVideo", "characterGazeMarker", "eyeTarget", "rtcAudio"];
        const nodes = ids.map(id => document.getElementById(id));
        if (nodes.some((node, i) => !node || document.querySelectorAll(`#${ids[i]}`).length !== 1)) throw Error("Missing/duplicate DOM");
        const [video, , marker, audio] = nodes;
        const gaze = CharacterGaze.getManager();
        if (gaze.videoElement !== video) throw Error("Initial tracking reference differs");
        const canvas = document.createElement("canvas"); canvas.width = 320; canvas.height = 240;
        const context = canvas.getContext("2d"); let color = 0, detections = 0;
        const draw = setInterval(() => { context.fillStyle = `hsl(${color++ % 360} 60% 50%)`; context.fillRect(0, 0, 320, 240); }, 40);
        const stream = canvas.captureStream(25);
        await gaze.initVision();
        if (!await gaze.initCamera(stream.getVideoTracks()[0], () => { detections++; })) throw Error("Tracking did not start");
        const videoStream = video.srcObject;
        const audioContext = new AudioContext(); await audioContext.resume();
        const oscillator = audioContext.createOscillator(), gain = audioContext.createGain(), destination = audioContext.createMediaStreamDestination();
        gain.gain.value = 0; oscillator.connect(gain).connect(destination); oscillator.start();
        const sender = new RTCPeerConnection(), receiver = new RTCPeerConnection(), abort = new AbortController();
        const failures = [];
        sender.onicecandidate = e => { if(e.candidate) receiver.addIceCandidate(e.candidate).catch(error => failures.push(String(error))); };
        receiver.onicecandidate = e => { if(e.candidate) sender.addIceCandidate(e.candidate).catch(error => failures.push(String(error))); };
        setupRtcRemoteTrackHandlers({ peerConnection: receiver, logger: DebugConsoleManager.getManager(), signal: abort.signal });
        sender.addTrack(destination.stream.getAudioTracks()[0], destination.stream);
        await sender.setLocalDescription(await sender.createOffer()); await receiver.setRemoteDescription(sender.localDescription);
        await receiver.setLocalDescription(await receiver.createAnswer()); await sender.setRemoteDescription(receiver.localDescription);
        audio.muted = true; await audio.play();
        const audioStream = audio.srcObject;
        marker.setAttribute("cx", "40%"); marker.setAttribute("cy", "45%"); marker.setAttribute("fill", "magenta");
        const verify = () => {
            if (nodes.some((node, i) => node !== document.getElementById(ids[i]) || document.querySelectorAll(`#${ids[i]}`).length !== 1)) throw Error("DOM replaced");
            if (video.srcObject !== videoStream || audio.srcObject !== audioStream || gaze.videoElement !== video) throw Error("Media reconnected");
            if (marker.getAttribute("cx") !== "40%") throw Error("Marker reset");
            if (failures.length) throw Error(failures.join(";"));
            return { detections, videoTime: video.currentTime, audioTime: audio.currentTime, audioPaused: audio.paused };
        };
        window.__debugDomCheck = { verify, app: SincroAppController.getCurrent(), cleanup: async () => { gaze.detachCamera(); clearInterval(draw); stream.getTracks().forEach(t => t.stop()); abort.abort(); sender.close(); receiver.close(); oscillator.stop(); await audioContext.close(); } };
        return verify();
    });
    await page.waitForFunction(() => window.__debugDomCheck.verify().detections > 0);
    await page.evaluate(() => window.__debugDomCheck.app.debug.showRightToolDebugPanel());
    await page.getByRole("tab", { name: "Gaze", exact: true }).click();
    await page.locator("#characterGazeVideo").waitFor({ state: "visible" });
    const visible = await page.evaluate(() => window.__debugDomCheck.verify());
    await page.getByRole("tab", { name: "Audio", exact: true }).click();
    await page.evaluate(() => window.__debugDomCheck.app.debug.hideRightToolDebugPanel());
    const hidden = await page.evaluate(() => window.__debugDomCheck.verify());
    await page.waitForFunction(previous => { const current = window.__debugDomCheck.verify(); return current.detections > previous.detections && current.audioTime > previous.audioTime; }, hidden);
    await page.evaluate(() => window.__debugDomCheck.app.debug.showRightToolDebugPanel());
    if (await page.getByRole("tab", { name: "Audio", exact: true }).getAttribute("aria-selected") !== "true") throw Error("Selected tab lost");
    await page.getByRole("tab", { name: "Gaze", exact: true }).click();
    const final = await page.evaluate(() => window.__debugDomCheck.verify());
    await page.screenshot({ path: "/tmp/sincro-debug-dom.png" });
    await page.evaluate(() => window.__debugDomCheck.cleanup());
    return { initial, visible, hidden, final, input: "合成映像・無音のWebRTC音声" };
}
